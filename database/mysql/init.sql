-- 适配器视图：将底层 PDF 字段统一映射为后端期望的字段名
-- 字段映射 (依据 PDF 表 3-17/3-18/3-19): id <- Sno/Cno, name <- Snm/Cnm, score/credits <- Grd/Cpt, teacher <- Tec, location <- Pla
CREATE VIEW vw_adapter_students AS
SELECT
    Sno                                  AS id,
    'C'                                  AS college,
    Snm                                  AS name,
    Sex                                  AS gender,
    Sde                                  AS major,
    CAST(LEFT(Sno, 4) AS UNSIGNED)       AS grade
FROM C_STUDENT;

CREATE VIEW vw_adapter_courses AS
SELECT
    Cno                                  AS id,
    'C'                                  AS college,
    Cnm                                  AS name,
    Ctm                                  AS hours,
    CAST(Cpt AS DECIMAL(3,1))            AS credits,
    Tec                                  AS teacher,
    Pla                                  AS location,
    (CASE WHEN Share = 'Y' THEN 1 ELSE 0 END) AS shared
FROM C_COURSE;

CREATE VIEW vw_adapter_enrollments AS
SELECT
    CONCAT(Cno, '-', Sno)                AS id,
    'C'                                  AS studentCollege,
    Sno                                  AS studentId,
    'C'                                  AS courseCollege,
    Cno                                  AS courseId,
    DATE_ADD('2026-03-01', INTERVAL (CAST(SUBSTRING(Cno, 2) AS UNSIGNED) - 1) DAY) AS enrolledAt,
    'ACTIVE'                             AS status,
    Grd                                  AS score
FROM C_SELECTION
UNION ALL
SELECT
    CONCAT(Cno, '-', student_no)          AS id,
    source_college                       AS studentCollege,
    student_no                           AS studentId,
    'C'                                  AS courseCollege,
    Cno                                  AS courseId,
    enrolled_on                          AS enrolledAt,
    status_code                          AS status,
    Grd                                  AS score
FROM C_IMPORTED_SELECTION;

