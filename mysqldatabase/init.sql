-- 创建数据库
CREATE DATABASE IF NOT EXISTS college_c CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE college_c;

-- 创建学生表
CREATE TABLE IF NOT EXISTS students (
    id VARCHAR(20) NOT NULL PRIMARY KEY COMMENT '学生ID',
    college_code ENUM('A', 'B', 'C') NOT NULL COMMENT '学院代码',
    name VARCHAR(50) NOT NULL COMMENT '学生姓名',
    gender ENUM('男', '女') NOT NULL COMMENT '性别',
    major VARCHAR(100) NOT NULL COMMENT '专业',
    grade INT NOT NULL COMMENT '年级'
) COMMENT '学生信息表';

-- 创建课程表
CREATE TABLE IF NOT EXISTS courses (
    id VARCHAR(20) NOT NULL PRIMARY KEY COMMENT '课程ID',
    college_code ENUM('A', 'B', 'C') NOT NULL COMMENT '学院代码',
    name VARCHAR(100) NOT NULL COMMENT '课程名称',
    credits DOUBLE NOT NULL COMMENT '学分',
    teacher VARCHAR(50) NOT NULL COMMENT '授课教师',
    shared BOOLEAN NOT NULL DEFAULT FALSE COMMENT '是否为共享课程'
) COMMENT '课程信息表';

-- 创建选课记录表
CREATE TABLE IF NOT EXISTS enrollments (
    id VARCHAR(20) NOT NULL PRIMARY KEY COMMENT '选课记录ID',
    student_college ENUM('A', 'B', 'C') NOT NULL COMMENT '学生所在学院',
    student_id VARCHAR(20) NOT NULL COMMENT '学生ID',
    course_college ENUM('A', 'B', 'C') NOT NULL COMMENT '课程所属学院',
    course_id VARCHAR(20) NOT NULL COMMENT '课程ID',
    enrolled_at DATE NOT NULL COMMENT '选课日期',
    status VARCHAR(20) NOT NULL COMMENT '选课状态'
) COMMENT '选课记录表';

